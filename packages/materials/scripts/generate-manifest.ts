import { readdir, readFile, mkdir, rename, writeFile, rm, stat } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import type { Material } from '../src/material';
import { format } from 'prettier';
import { commonMaterialProperties, commonInitEvent } from '../src/material-manifest';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'antd/generated/manifests.ts');
const generate = async () => {
  const definitions: string[] = [];
  const types = new Set<string>();
  for (const entry of (await readdir(join(root, 'antd'), { withFileTypes: true })).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (!entry.isDirectory()) continue;
    const config = join(root, 'antd', entry.name, 'material-config.ts');
    try {
      await readFile(config);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') continue;
      throw error;
    }
    const material = (await import(pathToFileURL(config).href)).default as Material;
    if (!/^[A-Za-z_$][\w$]*$/.test(material.type))
      throw new Error(`物料 type 无法用作导出名称: ${material.type}`);
    if (types.has(material.type)) throw new Error(`重复物料类型: ${material.type}`);
    types.add(material.type);
    const manifest = material.manifest;
    const data = {
      ...manifest,
      version: undefined,
      propsSchema: {
        ...manifest.propsSchema,
        properties: Object.fromEntries(
          Object.entries(manifest.propsSchema.properties as Record<string, unknown>).filter(
            ([key]) => !Object.hasOwn(commonMaterialProperties, key),
          ),
        ),
      },
      context: {
        ...manifest.context,
        events:
          JSON.stringify(manifest.context.events[0]) === JSON.stringify(commonInitEvent)
            ? manifest.context.events.slice(1)
            : manifest.context.events,
      },
    };
    // Reject executable and non-JSON numeric values instead of silently losing validation rules.
    const json = JSON.stringify(
      data,
      (_key, value: unknown) => {
        if (
          typeof value === 'function' ||
          typeof value === 'symbol' ||
          typeof value === 'bigint' ||
          (typeof value === 'number' && !Number.isFinite(value))
        )
          throw new Error(`${material.type}: Manifest 包含不可序列化值`);
        return value;
      },
      2,
    );
    definitions.push(
      `export const ${material.type}Manifest = withMaterialManifestDefaults(${json});`,
    );
  }
  const content = await format(
    `// Generated by scripts/generate-manifest.ts. Do not edit.\nimport { withMaterialManifestDefaults } from '../manifest-defaults';\n${definitions.join('\n')}\n`,
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  );
  let previous: string | undefined;
  try {
    previous = await readFile(output, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
  }
  if (process.argv.includes('--check')) {
    if (previous !== content)
      throw new Error(
        'Manifest 产物缺失或已过期，请运行 pnpm --filter @origamix/materials manifest:generate 并提交 antd/generated/manifests.ts',
      );
    console.info('Material manifests are up to date');
    return;
  }
  if (previous === content) return;
  await mkdir(join(root, 'antd/generated'), { recursive: true });
  const temporary = `${output}.${process.pid}.tmp`;
  try {
    await writeFile(temporary, content);
    await rename(temporary, output);
  } finally {
    await rm(temporary, { force: true });
  }
  console.info(`Generated ${types.size} material manifests`);
};

if (process.argv.includes('--watch')) {
  // Each run gets a fresh module graph, including transitive config dependencies.
  let stopping = false;
  let activeChild: ReturnType<typeof spawn> | undefined;
  let running = false;
  let dirty = false;
  let timer: ReturnType<typeof setTimeout>;
  const rebuild = async () => {
    if (stopping) return;
    if (running) {
      dirty = true;
      return;
    }
    running = true;
    do {
      dirty = false;
      const code = await new Promise<number | null>((resolve, reject) => {
        const child = spawn(process.execPath, ['--import', 'tsx', fileURLToPath(import.meta.url)], {
          cwd: root,
          stdio: 'inherit',
        });
        activeChild = child;
        child.once('error', reject);
        child.once('exit', resolve);
      });
      activeChild = undefined;
      if (code !== 0 && !stopping) console.error('Manifest 生成失败，请修复配置；现有产物未更新。');
    } while (dirty && !stopping);
    running = false;
  };
  // Poll only source trees: works on restricted/network filesystems without native watcher limits.
  const fingerprint = async () => {
    const files: string[] = [];
    const collect = async (path: string): Promise<void> => {
      if (path === join(root, 'antd/generated')) return;
      try {
        const info = await stat(path);
        if (info.isDirectory()) {
          for (const name of (await readdir(path)).sort()) await collect(join(path, name));
        } else {
          files.push(`${path}:${info.mtimeMs}:${info.size}`);
        }
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
      }
    };
    for (const path of [
      'antd',
      'src',
      'components',
      'utils',
      'scripts',
      'package.json',
      'tsconfig.json',
    ]) {
      await collect(join(root, path));
    }
    return files.join('\n');
  };
  let previous = await fingerprint();
  let scanning = false;
  const interval = setInterval(async () => {
    if (scanning || stopping) return;
    scanning = true;
    try {
      const current = await fingerprint();
      if (current !== previous) {
        previous = current;
        clearTimeout(timer);
        timer = setTimeout(() => void rebuild(), 100);
      }
    } catch (error) {
      console.error('Manifest watch 失败:', error);
      process.exitCode = 1;
      stop();
    } finally {
      scanning = false;
    }
  }, 500);
  const stop = () => {
    stopping = true;
    activeChild?.kill();
    clearTimeout(timer);
    clearInterval(interval);
  };
  process.once('SIGINT', stop);
  process.once('SIGTERM', stop);
  await rebuild();
} else {
  await generate();
}
